import { lt, type LText } from "../text";
import type { GtmChannel, SectorId } from "../types";

export interface SectorTrait {
  kind: "pro" | "con";
  title: LText;
  text: LText;
}

export interface SectorDef {
  id: SectorId;
  name: LText;
  tagline: LText;
  description: LText;
  icon: string;
  traits: SectorTrait[];
  /** Founders' savings + friends & family. */
  startingCash: number;
  /** Development points required to reach a launchable MVP. */
  mvpEffort: number;
  /** Total addressable market (number of potential paying customers). */
  tam: number;
  /** Monthly willingness to pay of an average customer for an average product. */
  refPrice: number;
  priceMin: number;
  priceMax: number;
  priceUnit: LText;
  /** Price elasticity of demand (higher = more price sensitive). */
  elasticity: number;
  /** Cost to acquire a customer with paid channels in a neutral market. */
  baseCac: number;
  /** Monthly churn of an average product. */
  baseChurn: number;
  grossMargin: number;
  /** Monthly referral rate generated by happy customers. */
  virality: number;
  /** 0 = none, 1 = strong two-sided network effects. */
  networkEffect: number;
  /** How much paid demand depends on a sales team to close deals (0-1). */
  salesDependence: number;
  /** Deals closed per month per point of sales capacity. */
  dealsPerSalesPoint: number;
  /** Customers one point of customer success capacity can look after. */
  customersPerCsPoint: number;
  /** ARR multiple for a typical company in the sector. */
  revenueMultiple: number;
  /** Typical pre-seed valuation of a credible team with an idea. */
  preRevenueValuation: number;
  npcCompetitors: number;
  /** CAC multiplier by channel (lower is better). */
  gtmFit: Record<GtmChannel, number>;
  /** Monthly compliance cost once launched (regulated sectors). */
  complianceCost: number;
  /** Appetite of acquirers for the sector (exit offers). */
  mnaHeat: number;
}

